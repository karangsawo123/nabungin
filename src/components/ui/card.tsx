export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      'rounded-2xl border border-[#1C2538] bg-[#101522] text-slate-100 shadow-sm transition-colors',
      interactive && 'hover:border-[#2A3650] hover:bg-[#141A2A] cursor-pointer',
      className
    )}
    {...props}
  />
))
Card.displayName = 'Card'

